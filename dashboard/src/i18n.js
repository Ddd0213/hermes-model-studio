export function resolveLocale(locale) {
  return /^zh(?:-|$)/i.test(String(locale || 'en')) ? 'zh' : 'en';
}

export function translate(value, locale) {
  if (typeof value !== 'string' || resolveLocale(locale) === 'zh') return value;
  const key = value.trim();
  if (Object.prototype.hasOwnProperty.call(EN, key)) {
    return value.slice(0, value.length - value.trimStart().length) + EN[key] + value.slice(value.trimEnd().length);
  }
  // Model IDs, parameter names and HTTP codes are data, not translation keys.
  const validation = key.match(/^(.*)(：最大输出必须小于上下文。|：请选择思考等级。|：思考预算至少 1024，并为回答保留 1024 Token。)$/);
  if (validation) return validation[1] + EN[validation[2]];
  const number = key.match(/^(.*) 的 (context_length|max_output_tokens|thinking_budget) 必须是范围内的正整数。$/);
  if (number) return number[1] + ': ' + number[2] + ' must be a positive integer within the allowed range.';
  const http = key.match(/^上游返回 HTTP (\d+)。请检查地址、密钥和接口格式；为保护密钥，不回传上游错误正文。$/);
  if (http) return 'The upstream API returned HTTP ' + http[1] + '. Check the URL, key, and API format. The upstream error body is not returned to protect your key.';
  const latency = key.match(/^(.+) · (\d+ ms)$/);
  if (latency) return translate(latency[1], locale) + ' · ' + latency[2];
  return value;
}
